const setPageLanguage = (lang) => {
  const dictionary = { ...pageTranslations[lang], ...pageTranslations[lang].pages[page] };
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = element.dataset.i18n.split('.').reduce((obj, key) => obj && obj[key], dictionary);
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.className = button.dataset.lang === lang ? 'text-white transition-colors' : 'text-neutral-500 transition-colors';
  });
  localStorage.setItem('rbclabs-language', lang);
};

document.querySelectorAll('[data-lang]').forEach((button) => button.addEventListener('click', () => setPageLanguage(button.dataset.lang)));
